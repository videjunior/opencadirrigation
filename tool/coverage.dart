/// Line coverage of the test suite, by folder, with floors.
///
///   dart run tool/coverage.dart imports [test/zz_all_libraries_test.dart]
///       writes a test that imports every library of lib/ the VM can load
///       (all but the browser-only ones), so that a file no test reaches
///       still shows in the report, at 0 %, instead of being left out
///   flutter test --coverage
///   dart run tool/coverage.dart report coverage/lcov.info [more.info...]
///       [--floor lib/core=95]... [--summary coverage/summary.md] [--merged coverage/merged.info]
///
/// The report merges the lcov files (the shards of CI), prints the line
/// coverage of every folder two levels under lib/ and the least covered
/// files, and exits with code 1 when a folder given with --floor is below
/// its percentage. CI runs both steps; the generated test is not committed.
library;

import 'dart:io';

void main(List<String> args) {
  if (args.isEmpty || !{'imports', 'report'}.contains(args.first)) {
    stderr.writeln('usage: dart run tool/coverage.dart imports [file] | report <lcov>... [--floor dir=percent]... [--summary file.md] [--merged file.info]');
    exit(2);
  }
  if (args.first == 'imports') {
    final out = args.length > 1 ? args[1] : 'test/zz_all_libraries_test.dart';
    final libs = vmLibraries();
    File(out).writeAsStringSync(renderImportsTest(libs));
    stdout.writeln('$out: imports ${libs.length} libraries');
    return;
  }
  final files = <String>[];
  final floors = <String, double>{};
  String? summary, merged;
  for (var i = 1; i < args.length; i++) {
    final a = args[i];
    if (a == '--floor' && i + 1 < args.length) {
      final kv = args[++i].split('=');
      final v = kv.length == 2 ? double.tryParse(kv[1]) : null;
      if (v == null) {
        stderr.writeln('--floor wants dir=percent, got ${args[i]}');
        exit(2);
      }
      floors[kv[0].endsWith('/') ? kv[0].substring(0, kv[0].length - 1) : kv[0]] = v;
    } else if (a == '--summary' && i + 1 < args.length) {
      summary = args[++i];
    } else if (a == '--merged' && i + 1 < args.length) {
      merged = args[++i];
    } else {
      files.add(a);
    }
  }
  if (files.isEmpty) {
    stderr.writeln('no lcov file given');
    exit(2);
  }
  final cov = Coverage();
  for (final f in files) {
    cov.addLcov(File(f).readAsStringSync());
  }
  if (merged != null) File(merged).writeAsStringSync(cov.toLcov());
  final report = cov.report(floors);
  stdout.write(report.text);
  if (summary != null) File(summary).writeAsStringSync(report.text);
  if (report.failed.isNotEmpty) {
    stderr.writeln('below the floor: ${report.failed.join(', ')}');
    exitCode = 1;
  }
}

/// Libraries of lib/ the VM can load: not part files, not the browser side
/// of the conditional imports (`*_web.dart`) nor the design worker.
List<String> vmLibraries() {
  final out = <String>[];
  for (final f in Directory('lib').listSync(recursive: true)) {
    if (f is! File || !f.path.endsWith('.dart')) continue;
    final path = f.path.replaceAll(r'\', '/');
    if (path.endsWith('_web.dart') || path.startsWith('lib/worker/')) continue;
    final text = f.readAsStringSync();
    if (RegExp(r'^part of\b', multiLine: true).hasMatch(text)) continue;
    if (RegExp(r'''^import\s+'(dart:js_interop|dart:html|package:web/)''', multiLine: true).hasMatch(text)) continue;
    out.add(path);
  }
  return out..sort();
}

String renderImportsTest(List<String> libs) {
  final b = StringBuffer()
    ..writeln('// GENERATED by `dart run tool/coverage.dart imports` for the coverage run; not committed.')
    ..writeln('// ignore_for_file: unused_import')
    ..writeln("import 'package:flutter_test/flutter_test.dart';")
    ..writeln();
  for (var i = 0; i < libs.length; i++) {
    b.writeln("import 'package:opencadirrigation/${libs[i].substring(4)}' as l$i;");
  }
  b
    ..writeln()
    ..writeln('/// Loads every library, so that the coverage report counts the lines of')
    ..writeln('/// the files no other test reaches.')
    ..writeln('void main() {')
    ..writeln("  test('every library of lib/ loads in the VM', () {});")
    ..writeln('}');
  return b.toString();
}

/// Hits by line, by source file.
class Coverage {
  final Map<String, Map<int, int>> files = {};

  void addLcov(String text) {
    Map<int, int>? lines;
    for (final raw in text.split('\n')) {
      final line = raw.trim();
      if (line.startsWith('SF:')) {
        var path = line.substring(3).replaceAll(r'\', '/');
        final at = path.indexOf('/lib/');
        if (!path.startsWith('lib/') && at >= 0) path = path.substring(at + 1);
        lines = files.putIfAbsent(path, () => {});
      } else if (line.startsWith('DA:') && lines != null) {
        final parts = line.substring(3).split(',');
        final n = int.tryParse(parts[0]), hits = parts.length > 1 ? int.tryParse(parts[1]) : null;
        if (n != null && hits != null) lines[n] = (lines[n] ?? 0) + hits;
      } else if (line == 'end_of_record') {
        lines = null;
      }
    }
  }

  String toLcov() {
    final b = StringBuffer();
    for (final f in files.keys.toList()..sort()) {
      final lines = files[f]!;
      b.writeln('SF:$f');
      for (final n in lines.keys.toList()..sort()) {
        b.writeln('DA:$n,${lines[n]}');
      }
      b
        ..writeln('LF:${lines.length}')
        ..writeln('LH:${lines.values.where((h) => h > 0).length}')
        ..writeln('end_of_record');
    }
    return b.toString();
  }

  /// Lines found and hit under [dir] (a folder or a file).
  (int, int) of(String dir) {
    var found = 0, hit = 0;
    for (final e in files.entries) {
      if (e.key != dir && !e.key.startsWith('$dir/')) continue;
      found += e.value.length;
      hit += e.value.values.where((h) => h > 0).length;
    }
    return (found, hit);
  }

  ({String text, List<String> failed}) report(Map<String, double> floors) {
    String pct(int found, int hit) => found == 0 ? '—' : '${(100 * hit / found).toStringAsFixed(1)} %';
    final b = StringBuffer()
      ..writeln('## Line coverage')
      ..writeln()
      ..writeln('| Folder | Lines | Covered | Coverage |')
      ..writeln('|---|---:|---:|---:|');
    final (allFound, allHit) = of('lib');
    b.writeln('| **lib** | $allFound | $allHit | **${pct(allFound, allHit)}** |');
    final folders = <String>{
      for (final f in files.keys)
        if (f.startsWith('lib/')) f.split('/').length > 3 ? f.split('/').take(3).join('/') : f.split('/').take(2).join('/'),
    }.toList()..sort();
    for (final d in folders) {
      final (found, hit) = of(d);
      b.writeln('| $d | $found | $hit | ${pct(found, hit)} |');
    }
    final failed = <String>[];
    if (floors.isNotEmpty) {
      b
        ..writeln()
        ..writeln('| Floor | Required | Coverage | |')
        ..writeln('|---|---:|---:|---|');
      for (final e in floors.entries) {
        final (found, hit) = of(e.key);
        final value = found == 0 ? 0.0 : 100 * hit / found;
        final ok = found > 0 && value + 1e-9 >= e.value;
        if (!ok) failed.add('${e.key} ${value.toStringAsFixed(1)} % < ${e.value} %');
        b.writeln('| ${e.key} | ${e.value} % | ${pct(found, hit)} | ${ok ? 'ok' : '**below**'} |');
      }
    }
    final worst = [
      for (final e in files.entries)
        if (e.key.startsWith('lib/') && e.value.length >= 50) (e.key, e.value.length, e.value.values.where((h) => h > 0).length),
    ]..sort((a, b) => (a.$3 / a.$2).compareTo(b.$3 / b.$2));
    b
      ..writeln()
      ..writeln('Least covered files (50 lines or more):')
      ..writeln()
      ..writeln('| File | Lines | Coverage |')
      ..writeln('|---|---:|---:|');
    for (final w in worst.take(15)) {
      b.writeln('| ${w.$1} | ${w.$2} | ${pct(w.$2, w.$3)} |');
    }
    return (text: b.toString(), failed: failed);
  }
}
