#!/usr/bin/env python3
"""Writes lib/core/io/codepages_cjk_data.dart: the tables of the East Asian
double-byte code pages the DXF, DWG and DBF readers take (932 Japanese
Shift-JIS, 936 Simplified Chinese GBK, 949 Korean, 950 Traditional Chinese
Big5), from the codecs of the Python standard library (the Windows
mappings: cp932, gbk, cp949, cp950). No package is needed:

    python3 -I tool/formats/gen_codepages_cjk.py

Each table is zlib-compressed and in base64:
  128 × uint16 LE  the characters of the single bytes 0x80-0xFF (0: none)
  uint8            the number of lead bytes
  per lead byte: uint8 the lead, then 192 × uint16 LE for the trail bytes
  0x40-0xFF, each the difference from the previous character of the row
  (modulo 2^16), 0 for a pair with no character.
The output is the same on every run.
"""
import base64
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'lib' / 'core' / 'io' / 'codepages_cjk_data.dart'

PAGES = [(932, 'cp932', 'Japanese (Shift-JIS)'), (936, 'gbk', 'Simplified Chinese (GBK)'), (949, 'cp949', 'Korean (Unified Hangul Code)'), (950, 'cp950', 'Traditional Chinese (Big5)')]


def table(codec):
    raw = bytearray()
    for b in range(0x80, 0x100):
        try:
            s = bytes([b]).decode(codec)
            raw += struct.pack('<H', ord(s) if len(s) == 1 and ord(s) <= 0xFFFF else 0)
        except UnicodeDecodeError:
            # Windows' 936 has the euro sign at 0x80 (Python's GBK does not)
            raw += struct.pack('<H', 0x20AC if codec == 'gbk' and b == 0x80 else 0)
    rows = {}
    for lead in range(0x81, 0x100):
        row = [0] * 256
        ok = False
        for t in range(0x40, 0x100):
            try:
                s = bytes([lead, t]).decode(codec)
            except UnicodeDecodeError:
                continue
            if len(s) == 1 and 0x7F < ord(s) <= 0xFFFF:
                row[t] = ord(s)
                ok = True
        if ok:
            rows[lead] = row
    raw.append(len(rows))
    for lead, row in sorted(rows.items()):
        raw.append(lead)
        prev = 0
        for v in row[0x40:]:
            raw += struct.pack('<H', ((v - prev) & 0xFFFF) if v else 0)
            if v:
                prev = v
    return base64.b64encode(zlib.compress(bytes(raw), 9)).decode('ascii')


def main():
    lines = [
        '// Generated by tool/formats/gen_codepages_cjk.py from the codecs of the',
        '// Python standard library (the Windows mappings of the code pages).',
        '// Do not edit by hand.',
        '// dart format off',
        '',
        '/// Tables of the East Asian double-byte code pages, compressed (see',
        '/// tool/formats/gen_codepages_cjk.py for the layout). Loaded on demand by',
        '/// codepages.dart (a deferred library: not in the main program).',
        'library;',
        '',
        'const cjkTables = <int, String>{',
    ]
    for cp, codec, name in PAGES:
        data = table(codec)
        lines.append(f'  // {cp}: {name}')
        lines.append(f'  {cp}:')
        for i in range(0, len(data), 180):
            chunk = data[i:i + 180]
            end = ',' if i + 180 >= len(data) else ''
            lines.append(f"      '{chunk}'{end}")
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
