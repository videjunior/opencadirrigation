/// Writes lib/app/version.dart from the `version:` line of pubspec.yaml and
/// stamps today's date as the release date of that version.
///
/// Run after bumping the version in pubspec.yaml:
///   dart run tool/gen_version.dart
///
/// Published builds add the git commit and the build date on top of it with
/// tool/build_web.sh (passed as --dart-define values, see version.dart).
library;

import 'dart:io';

void main() {
  final pubspec = File('pubspec.yaml').readAsStringSync();
  final m = RegExp(r'^version:\s*(\d+\.\d+\.\d+)(?:\+(\d+))?\s*$', multiLine: true).firstMatch(pubspec);
  if (m == null) {
    stderr.writeln('pubspec.yaml: no "version: x.y.z+n" line');
    exit(1);
  }
  final version = m.group(1)!;
  final build = int.parse(m.group(2) ?? '0');
  final now = DateTime.now();
  String two(int v) => v.toString().padLeft(2, '0');
  final date = '${now.year}-${two(now.month)}-${two(now.day)}';
  File('lib/app/version.dart').writeAsStringSync(renderVersionDart(version: version, build: build, releaseDate: date));
  stdout.writeln('lib/app/version.dart: $version+$build, released $date');
}

String renderVersionDart({required String version, required int build, required String releaseDate}) => '''
/// Application version. GENERATED by `dart run tool/gen_version.dart` from
/// the `version:` line of pubspec.yaml; do not edit by hand. Bump the version
/// in pubspec.yaml and run the tool again (it also stamps the release date).
///
/// Published builds add the git commit and the build date through
/// tool/build_web.sh, which passes them as --dart-define values.
library;

const appName = 'OpenCADIrrigation';

/// Semantic version: the pubspec `version` before the `+`.
const appVersion = '$version';

/// Build number: the pubspec `version` after the `+`.
const appBuild = $build;

/// Date this version was generated (release date of [appVersion]).
const appReleaseDate = '$releaseDate';

/// Short git commit of the build (`--dart-define=OCI_COMMIT=…`), else empty.
const appCommit = String.fromEnvironment('OCI_COMMIT');

/// Build date (`--dart-define=OCI_BUILD_DATE=…`), else the release date.
const appBuildDate = String.fromEnvironment('OCI_BUILD_DATE', defaultValue: appReleaseDate);

/// `x.y.z+n`, the pubspec form.
const appVersionFull = '\$appVersion+\$appBuild';

/// Everything that identifies the build, shown at start-up (welcome dialog,
/// status bar, console) and in Help → About:
/// `1.0.0 (build 1) · 2026-09-16 · git 86c06b2`.
String get appVersionLabel => [
  '\$appVersion (build \$appBuild)',
  appBuildDate,
  if (appCommit.isNotEmpty) 'git \$appCommit',
].join(' · ');

/// Public site.
const appSiteUrl = 'https://opencadirrigation.com';
''';
