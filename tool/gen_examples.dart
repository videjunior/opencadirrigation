/// Writes the example gallery as project files: `examples/<lang>/<id>.oci.json`
/// for every interface language, plus examples/README.md.
/// Run: dart run tool/gen_examples.dart
/// The test test/core/examples_test.dart fails when the files are out of
/// date with the builders in lib/app/examples.dart.
library;
import 'dart:convert';
import 'dart:io';

import 'package:opencadirrigation/app/examples.dart';
import 'package:opencadirrigation/app/i18n.dart';

/// Installs every `assets/i18n/<code>.json` pack, so the seventeen languages
/// that are not compiled in translate here exactly as they do in the app
/// (the step test/support/language_packs.dart takes for the tests).
void installPacksFromDisk() {
  final dir = Directory('assets/i18n');
  if (!dir.existsSync()) {
    stderr.writeln('assets/i18n not found: run this tool from the repository root');
    exit(1);
  }
  for (final f in dir.listSync().whereType<File>()) {
    if (!f.path.endsWith('.json')) continue;
    final code = f.uri.pathSegments.last.replaceAll('.json', '');
    installLanguagePack(code, LanguagePack.fromJson(jsonDecode(f.readAsStringSync()) as Map<String, dynamic>));
  }
  final missing = supportedLanguages.where((l) => !isLanguageLoaded(l)).toList();
  if (missing.isNotEmpty) {
    stderr.writeln('no string table for ${missing.join(', ')}: the files would come out in English');
    exit(1);
  }
}

/// Wraps [words] into lines of at most [width] characters, for the README.
String _wrap(List<String> words, {int width = 100, String sep = ', '}) {
  final lines = <String>[];
  var line = '';
  for (final w in words) {
    final piece = line.isEmpty ? w : '$line$sep$w';
    if (piece.length > width && line.isNotEmpty) {
      lines.add('$line${sep.trimRight()}');
      line = w;
    } else {
      line = piece;
    }
  }
  if (line.isNotEmpty) lines.add(line);
  return lines.join('\n');
}

void main() {
  installPacksFromDisk();
  final created = DateTime.utc(2026, 9, 16);
  final folders = _wrap([for (final l in supportedLanguages) '`$l/` ${languageNames[l]}']);
  final readme = StringBuffer()
    ..writeln('# Example projects (`.oci.json`)')
    ..writeln()
    ..writeln('Ready-made projects to open in OpenCADIrrigation (File → Open project…) or from the gallery of')
    ..writeln('the welcome screen (Help → Welcome and example gallery…; `?example=<id>` in the URL opens one')
    ..writeln('directly). Each of them designs with F5 or ▶. Generated by `dart run tool/gen_examples.dart` from')
    ..writeln('`lib/app/examples.dart`, one folder per interface language:')
    ..writeln()
    ..writeln('$folders.')
    ..writeln()
    ..writeln('The projects are the same drawing in every language: what changes is the text — project name,')
    ..writeln('client and site, zone, area and pipe names, crops and the catalogue item names. The table below')
    ..writeln('names them in English (`en/`).')
    ..writeln();
  final en = I18n('en');
  readme.writeln('| id | project | contents |');
  readme.writeln('|---|---|---|');
  for (final ex in exampleGallery) {
    readme.writeln('| `${ex.id.name}` | ${en(ex.titleKey)} — ${en(ex.tagsKey)} | ${en(ex.subtitleKey)} |');
  }
  var n = 0;
  var bytes = 0;
  for (final lang in supportedLanguages) {
    final dir = Directory('examples/$lang')..createSync(recursive: true);
    for (final ex in exampleGallery) {
      final p = buildExample(ex.id, I18n(lang).call, lang: lang);
      p.meta.uid = 'example-${ex.id.name}-$lang';
      p.meta.created = created;
      final j = p.toJson();
      final f = File('${dir.path}/${ex.id.name}.oci.json');
      f.writeAsStringSync('${const JsonEncoder.withIndent('  ').convert(j)}\n');
      n++;
      bytes += f.lengthSync();
    }
    stdout.writeln('examples/$lang: ${exampleGallery.length} projects (${languageNames[lang]})');
  }
  File('examples/README.md').writeAsStringSync(readme.toString());
  stdout.writeln('$n files, ${(bytes / (1024 * 1024)).toStringAsFixed(1)} MB');
}
