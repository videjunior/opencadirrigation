/// Operations of the engineering side of the program for the AI assistant
/// (reached through run_operation): analyses, calculators, mechanised
/// machines, catalogue, proposal, sheets and exports.
///
/// They are not sent with each request: the model finds them with
/// find_operations and runs them with run_operation, which checks the input
/// against each schema and follows each effect (read, write = an undo step,
/// export = a file always confirmed, network = a request to another
/// service). [engineeringCoverage] maps every user-reachable function of
/// the engineering menus, panels and dialogs to the tool, operation,
/// command or setting that reaches it.
