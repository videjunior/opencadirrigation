/// What the AI assistant reaches of the program: every function a user can
/// reach — menu items (desktop and phone), command actions, drawing tools,
/// command aliases, dialogs and their options, the panels, the status bar
/// and the view options — mapped to what the model uses for it.
///
/// Keys: `action:<CadAction>`, `tool:<ToolId>`, `alias:<command alias>`,
/// `menu:<i18n key of the item label>` (keys of composite labels joined
/// with `+`, e.g. `menu:tool.misc+scope.mainline`), `dialog:<file stem>.<dialog>`
/// for each `show…` function of lib/app/widgets/dialogs (name without
/// "show" and "Dialog", e.g. `dialog:dialogs.units`) and
/// `dialog:<file stem>.<dialog>.<option>` for its options,
/// `panel:<panel>.<field>`, `status:<toggle>`, `view:<option>`.
///
/// Values: `tool:<name>` (sent with every request), `op:<name>` (through
/// find_operations / run_operation), `command:<alias>` (run_command),
/// `setting:<key>` (get_setting / set_setting), or `n/a:<reason>` for what
/// has no meaning for the AI or needs the user's hands (the About box,
/// the tutorial, the device's GPS…).
///
/// [coreCoverage] holds what the tools sent with every request cover;
/// `cadCoverage` (agent_ops_cad.dart) the drawing side's operations,
/// commands and settings; `engineeringCoverage` (agent_ops_engineering.dart)
/// the engineering side. test/widget_ai_coverage_test.dart fails on a
/// function without an entry or an entry whose target does not exist, and
/// writes docs/AI_TOOLS.md from this map.
